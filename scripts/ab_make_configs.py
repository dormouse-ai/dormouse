"""Emit the paired run configs for the FLOPs-per-byte A/B.

One overlay is appended to each stack config: same source slice, same held-out file,
same tokenizer, same batch/seq, same step count, one seed per file. The four arm
families differ only in the two stack values under test, so a BPB delta is
attributable to those values and nothing else.

    .venv/bin/python scripts/ab_make_configs.py configs/ab
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STACK = {
    "ctrl": ROOT / "configs" / "dormouse_1b.toml",
    "arm": ROOT / "configs" / "dormouse_1b_top1_r192.toml",
    "topk1": ROOT / "configs" / "dormouse_1b.toml",
    "r192": ROOT / "configs" / "dormouse_1b.toml",
}
CHANGES = {
    "ctrl": {},
    "arm": {},  # the arm file already carries topk=1 and rank=192
    "topk1": {"topk": "1"},
    "r192": {"expert_tsct_rank": "192"},
}
SOURCE = "/tmp/opencode/ab_data/mix_smoke_clamped.bin"
HELD_OUT = "/tmp/opencode/ab_data/holdout_clamped.bin"

OVERLAY = """\
# paired A/B run config -- generated by scripts/ab_make_configs.py; do not hand-edit.
schedule = "cosine"
seed = {seed}
warmup = {warmup}
eval_every = 0
ckpt_every = 0
eval_batches = 8
harness = false
eval = "{held_out}"

[[source]]
path = "{source}"
weight = 1.0
"""


def build(
    family: str,
    seed: int,
    *,
    tokens: int = 8_192_000,
    batch: int = 4,
    seq: int = 512,
    warmup: int = 400,
    lr_muon: float | None = None,
    lr_adamw: float | None = None,
) -> str:
    """Return one run config's text: the stack, the two under-test keys, the overlay."""
    text = STACK[family].read_text(encoding="utf-8")
    lines = text.splitlines()
    for key, value in CHANGES[family].items():
        lines = [
            f"{key} = {value}" if line.split("=", 1)[0].strip() == key else line
            for line in lines
        ]
    head = "\n".join(lines)
    # The stack files declare the full-corpus budget and the shipped batch; the run
    # overrides both so four thousand steps are a slice, not the 10 B-token plan.
    for key, value in (("tokens", str(tokens)), ("batch", str(batch)), ("seq_len", str(seq))):
        head = "\n".join(
            f"{key} = {value}" if line.split("=", 1)[0].strip() == key else line
            for line in head.splitlines()
        )
    rates = ""
    if lr_muon is not None:
        rates += f"lr_muon = {lr_muon}\n"
    if lr_adamw is not None:
        rates += f"lr_adamw = {lr_adamw}\n"
    return (
        head
        + "\n\n"
        + rates
        + OVERLAY.format(seed=seed, source=SOURCE, held_out=HELD_OUT, warmup=warmup)
    )


def main() -> int:
    """Write three seeds per family into the requested directory."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("outdir", help="where to write <family>_s<seed>.toml")
    parser.add_argument("--steps", type=int, default=4000, help="absolute step horizon")
    parser.add_argument("--batch", type=int, default=4)
    parser.add_argument("--seq", type=int, default=512)
    parser.add_argument("--warmup", type=int, default=400)
    parser.add_argument("--lr-muon", type=float, default=None)
    parser.add_argument("--lr-adamw", type=float, default=None)
    parser.add_argument("--families", default="ctrl,arm,topk1,r192")
    parser.add_argument("--seeds", default="0,1,2")
    args = parser.parse_args()

    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    tokens = args.steps * args.batch * args.seq
    for family in args.families.split(","):
        for seed in (int(value) for value in args.seeds.split(",")):
            path = out / f"{family}_s{seed}.toml"
            path.write_text(
                build(
                    family,
                    seed,
                    tokens=tokens,
                    batch=args.batch,
                    seq=args.seq,
                    warmup=args.warmup,
                    lr_muon=args.lr_muon,
                    lr_adamw=args.lr_adamw,
                ),
                encoding="utf-8",
            )
            print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
